//! The studio presets that ship with Tequila, written as code:
//! `cargo run -p tequila-format --example builtin_studios` writes them to
//! `assets/studios` (`docs/studio-presets.md`).
//!
//! Generic and made here: lit by the built-in studio environment and the
//! softboxes painted on it, so there are no pictures to license, and framed
//! for a product about 20 cm across. A thumbnail already in a preset's
//! folder is kept; one is rendered with
//! `tequila --studio-preset assets/studios/<id> --studio Hero -w 400 -h 300 -o assets/studios/<id>/thumbnail.png`.

use std::f32::consts::{FRAC_PI_2, PI};
use std::path::Path;
use tequila_core::math::{vec3, Vec3};
use tequila_render_core::camera::{Camera, Projection};
use tequila_scene::document::{EnvironmentSettings, GroundSettings};
use tequila_scene::lighting::SavedCamera;
use tequila_scene::preset::{Framing, FramingScale, StudioPreset};
use tequila_scene::render::{AlphaMode, BitDepth, OutputFormat, RenderSettings};
use tequila_scene::studio::Studio;

/// The bounding-sphere radius the cameras are framed for.
const RADIUS: f32 = 0.1;

/// A camera looking at the product's middle from `direction`, far enough
/// that a product of [`RADIUS`] fills the 4:3 frame with a margin.
fn camera(name: &str, direction: Vec3, up: Vec3, focal_length_mm: f32) -> SavedCamera {
    let target = vec3(0.0, 0.45 * RADIUS, 0.0);
    let half_height = (13.5 / focal_length_mm).atan();
    let distance = RADIUS * 1.15 / half_height.sin();
    let mut camera = Camera::look_at(target + direction.normalize() * distance, target, up);
    camera.projection = Projection::Perspective { focal_length_mm };
    SavedCamera { name: name.into(), camera, target }
}

fn view(name: &str, camera: &SavedCamera, yaw: f32) -> Studio {
    Studio { name: name.into(), camera: Some(camera.clone()), product_yaw: Some(yaw), ..Studio::default() }
}

fn soft_studio() -> StudioPreset {
    let hero = camera("Hero", vec3(0.62, 0.42, 0.66), Vec3::Y, 85.0);
    let front = camera("Front", vec3(0.0, 0.12, 1.0), Vec3::Y, 85.0);
    let top = camera("Top", vec3(0.0, 1.0, 0.001), -Vec3::Z, 85.0);
    let environment = EnvironmentSettings {
        image: None,
        pins: tequila_render_core::pins::studio_preset("Three-point").unwrap_or_default(),
        ground: GroundSettings {
            enabled: true,
            shadows: true,
            reflections: 0.25,
            reflection_blur: 0.05,
            reflection_fade_distance: 0.03,
            ..GroundSettings::default()
        },
        ..EnvironmentSettings::default()
    };
    StudioPreset {
        id: "tequila-soft-studio".into(),
        name: "Soft Studio".into(),
        family: "Tequila Studio".into(),
        size: "Medium".into(),
        description: "Three softboxes on a seamless floor with a soft shadow and a short reflection: a hero three-quarter, \
                      front, side, back and top views, rendered as transparent 16-bit PNGs."
            .into(),
        tags: vec!["product".into(), "softbox".into(), "transparent".into(), "built-in".into()],
        version: "1".into(),
        environment,
        lighting: Default::default(),
        render: RenderSettings {
            width: 2000,
            height: 1500,
            max_samples: 256,
            format: OutputFormat::Png,
            depth: BitDepth::Sixteen,
            alpha_mode: AlphaMode::Straight,
            filename_template: "{product}_{view}_{date}".into(),
            ..RenderSettings::default()
        },
        image_style: Default::default(),
        lights: Vec::new(),
        cameras: vec![hero.clone(), front.clone(), top.clone()],
        studios: vec![
            view("Hero", &hero, 0.0),
            view("Front", &front, 0.0),
            view("Side", &front, -FRAC_PI_2),
            view("Back", &front, PI),
            view("Top", &top, 0.0),
        ],
        framing: Framing { reference_radius: RADIUS, base_offset: 0.0, scale: FramingScale::Cameras },
        materials: Vec::new(),
        material_rules: Vec::new(),
        notes: "Generated by crates/tequila-format/examples/builtin_studios.rs.".into(),
    }
}

/// A catalogue studio: the product cut out on white with a short
/// reflection under it, as a web shop or a data sheet shows it.
///
/// Lit so that a flat top stays its own colour. Seen from high in front,
/// a top face mirrors whatever is high behind the product, so nothing
/// bright is put there: the key is to one side in front, the large soft
/// source overhead is forward of the product, and what is behind is a low,
/// narrow strip that only draws the far edges. A softbox behind and above,
/// the usual rim, lays a pale veil over every glossy top.
fn catalogue_studio() -> StudioPreset {
    use tequila_core::math::Vec2;
    use tequila_render_core::pins::{softbox, Pin};
    let main = camera("Main", vec3(0.0, 0.82, 0.57), Vec3::Y, 85.0);
    let side = camera("Side", vec3(0.0, 0.2, 1.0), Vec3::Y, 85.0);
    let top = camera("Top", vec3(0.0, 1.0, 0.001), -Vec3::Z, 85.0);
    // Bearings run from behind the product (0) round to in front of it
    // (180), where the cameras are.
    let wide = |pin: Pin, width: f32, height: f32| Pin { angular_size: Vec2 { x: width, y: height }, ..pin };
    let pins = vec![
        softbox("Key", -130.0, 38.0, 0.7, 0.5, 10.0),
        softbox("Overhead", 150.0, 68.0, 0.9, 0.7, 2.6),
        softbox("Fill", 118.0, 17.0, 1.0, 0.8, 3.0),
        wide(softbox("Front", 180.0, 11.0, 1.2, 0.8, 1.5), 1.2, 0.45),
        wide(softbox("Back strip", 0.0, 20.0, 1.6, 0.4, 5.0), 1.6, 0.12),
    ];
    let environment = EnvironmentSettings {
        image: None,
        pins,
        background: tequila_scene::document::BackgroundMode::Color,
        background_color: tequila_core::spectrum::Spectrum::splat(1.0),
        ground: GroundSettings {
            enabled: true,
            shadows: false,
            reflections: 0.3,
            reflection_blur: 0.02,
            reflection_fade_distance: 0.05,
            ..GroundSettings::default()
        },
        ..EnvironmentSettings::default()
    };
    let mut preset = StudioPreset {
        id: "tequila-catalogue-studio".into(),
        name: "Catalogue Studio".into(),
        family: "Tequila Studio".into(),
        size: "Medium".into(),
        description: "The product cut out on white with a short reflection, lit so a flat top keeps its colour: a main view                       from high in front, left, right, rear and top, rendered as transparent 16-bit PNGs at 3000 by 2250."
            .into(),
        tags: vec!["product".into(), "catalogue".into(), "packshot".into(), "white".into(), "transparent".into(), "built-in".into()],
        version: "1".into(),
        environment,
        lighting: Default::default(),
        render: RenderSettings {
            width: 3000,
            height: 2250,
            max_samples: 512,
            format: OutputFormat::Png,
            depth: BitDepth::Sixteen,
            alpha_mode: AlphaMode::Straight,
            filename_template: "{product}_{view}_{date}".into(),
            ..RenderSettings::default()
        },
        image_style: Default::default(),
        lights: Vec::new(),
        cameras: vec![main.clone(), side.clone(), top.clone()],
        studios: vec![
            view("Main", &main, 0.0),
            view("Left", &side, FRAC_PI_2),
            view("Right", &side, -FRAC_PI_2),
            view("Rear", &side, PI),
            view("Top", &top, 0.0),
        ],
        framing: Framing { reference_radius: RADIUS, base_offset: 0.0, scale: FramingScale::Cameras },
        materials: Vec::new(),
        material_rules: Vec::new(),
        notes: "Generated by crates/tequila-format/examples/builtin_studios.rs.".into(),
    };
    // A bright, saturated colour stays that colour, as a catalogue wants
    // it: the plain sRGB curve, a little under, where the default eases
    // highlights towards white.
    preset.image_style.display = tequila_color::DisplayTransform::Srgb;
    preset.image_style.exposure = -0.35;
    preset
}

fn main() {
    let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../assets/studios");
    for preset in [soft_studio(), catalogue_studio()] {
        let folder = root.join(&preset.id);
        let file = tequila_format::studio_preset::write_folder(&preset, &folder, None).expect("writes");
        println!("wrote {}", file.display());
    }
}
